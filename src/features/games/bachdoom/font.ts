const ORDER = Object.keys(GL)
const IDX: Record<string, number> = {}
ORDER.forEach((c, i) => { IDX[c] = i })
const CW = 6
const cache = new Map<string, HTMLCanvasElement>()

function atlas(color: string): HTMLCanvasElement {
  let c = cache.get(color)
  if (c) return c
  c = document.createElement('canvas')
  c.width = ORDER.length * CW; c.height = 7
  const g = c.getContext('2d')!
  g.fillStyle = color
  ORDER.forEach((ch, i) => {
    GL[ch].split('|').forEach((row, y) => { for (let x = 0; x < 5; x++) if (row[x] === '#') g.fillRect(i * CW + x, y, 1, 1) })
  })
  cache.set(color, c)
  return c
}

export const textWidth = (s: string, scale: number) => Math.max(0, s.length * CW - 1) * scale
export const textHeight = (scale: number) => 7 * scale

/** Draw text (upper-cased) with the pixel font. scale = device pixels per font pixel. */
export function drawText(g: CanvasRenderingContext2D, s: string, x: number, y: number, scale: number, color: string, opts?: { shadow?: string; align?: 'left' | 'center' | 'right' }) {
  scale = Math.max(1, Math.round(scale))
  const up = s.toUpperCase()
  const w = textWidth(up, scale)
  let px = Math.round(opts?.align === 'center' ? x - w / 2 : opts?.align === 'right' ? x - w : x)
  const py = Math.round(y)
  g.imageSmoothingEnabled = false
  const a = atlas(color), sh = opts?.shadow ? atlas(opts.shadow) : null
  for (let i = 0; i < up.length; i++) {
    const k = IDX[up[i]] ?? IDX['?']
    if (up[i] !== ' ') {
      if (sh) g.drawImage(sh, k * CW, 0, 5, 7, px + scale, py + scale, 5 * scale, 7 * scale)
      g.drawImage(a, k * CW, 0, 5, 7, px, py, 5 * scale, 7 * scale)
    }
    px += CW * scale
  }
}
